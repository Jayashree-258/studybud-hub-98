interface PdfNote {
  title: string;
  subject: string;
  unit?: string | null;
  summary?: string | null;
  contentHtml: string;
  questions: { question: string; answer: string | null; marks: number | null }[];
}

/** Opens a clean, printable document in a new window; the user saves it as PDF. */
export function downloadNoteAsPdf(note: PdfNote) {
  const win = window.open("", "_blank");
  if (!win) return false;

  const questionsHtml = note.questions.length
    ? `<h2>Important Questions</h2><ol>${note.questions
        .map(
          (q) =>
            `<li><strong>${escapeHtml(q.question)}</strong>${q.marks ? ` <em>(${q.marks} marks)</em>` : ""}${q.answer ? `<p>${escapeHtml(q.answer)}</p>` : ""}</li>`,
        )
        .join("")}</ol>`
    : "";

  win.document.write(`<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${escapeHtml(note.title)} — Life Saver</title>
<style>
  body { font-family: Georgia, serif; color: #1a2332; max-width: 720px; margin: 0 auto; padding: 48px 32px; line-height: 1.65; }
  .cover { text-align: center; border-bottom: 3px solid #155e6e; padding-bottom: 24px; margin-bottom: 32px; }
  .brand { font-size: 13px; letter-spacing: 3px; text-transform: uppercase; color: #155e6e; font-weight: bold; }
  h1 { font-size: 28px; margin: 16px 0 8px; }
  .meta { color: #5a6b7d; font-size: 14px; }
  h2 { color: #155e6e; font-size: 20px; margin-top: 28px; border-bottom: 1px solid #d8dee4; padding-bottom: 4px; }
  table { border-collapse: collapse; width: 100%; font-size: 14px; }
  th, td { border: 1px solid #d8dee4; padding: 6px 10px; text-align: left; }
  th { background: #f2f5f7; }
  pre { background: #1a2332; color: #f2f5f7; padding: 12px 14px; border-radius: 6px; font-size: 13px; overflow-x: auto; }
  .footer { margin-top: 48px; text-align: center; font-size: 12px; color: #8a97a5; border-top: 1px solid #d8dee4; padding-top: 12px; }
  @media print { body { padding: 0; } }
</style>
</head>
<body>
  <div class="cover">
    <div class="brand">Life Saver — UG Notes</div>
    <h1>${escapeHtml(note.title)}</h1>
    <div class="meta">${escapeHtml(note.subject)}${note.unit ? ` · ${escapeHtml(note.unit)}` : ""}</div>
    ${note.summary ? `<p class="meta">${escapeHtml(note.summary)}</p>` : ""}
  </div>
  <main>${note.contentHtml}</main>
  ${questionsHtml}
  <div class="footer">Generated by Life Saver · ${new Date().toLocaleDateString()}</div>
  <script>window.onload = () => { window.print(); }</script>
</body>
</html>`);
  win.document.close();
  return true;
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
